import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises"
import { watch } from "node:fs"
import { dirname, join } from "node:path"

const root = join(import.meta.dir, "..")
const registryDir = join(root, "registry", "ui")
const registryJson = join(registryDir, "registry.json")
const exampleDir = join(root, "example")
const exampleSrc = join(exampleDir, "src")
const exampleMessages = join(exampleSrc, "messages")
const exampleI18n = join(exampleSrc, "i18n")
const hooginDir = join(exampleSrc, "hoogin")

const watchMode = process.argv.includes("--watch")
const reverse = process.argv.includes("--reverse")

type RegistryFile = { path: string; target: string }
type RegistryItem = { name: string; files?: RegistryFile[] }

async function loadFiles(): Promise<RegistryFile[]> {
  const raw = JSON.parse(await readFile(registryJson, "utf8"))
  return (raw.items ?? []).flatMap((item: RegistryItem) => item.files ?? [])
}

// example path derives from the install target the way the shadcn CLI resolves it
// in a src/ project: `~/x` → example/x (project root), anything else → example/src/x
// (hoogin/..., messages/registry/..., i18n/...).
// registry path is the declared payload path relative to registry/ui/.
function examplePathFor(target: string) {
  return target.startsWith("~/")
    ? join(exampleDir, target.slice(2))
    : join(exampleSrc, target)
}

function pairFor(file: RegistryFile) {
  return {
    name: file.path,
    example: examplePathFor(file.target),
    registry: join(registryDir, file.path),
  }
}

async function syncPair(pair: { name: string; from: string; to: string }) {
  await mkdir(dirname(pair.to), { recursive: true })
  await copyFile(pair.from, pair.to)
  console.log(`synced ${pair.name}`)
}

async function generateRegistryConfig() {
  const raw = JSON.parse(await readFile(registryJson, "utf8"))
  const lines = [
    "// GENERATED FILE — do not edit manually.",
    "// Regenerated by `bun run scripts/sync.ts` from registry/ui/registry.json.",
    "",
    "export type RegistryItemFile = {",
    "  path: string",
    "  type: string",
    "  target: string",
    "}",
    "",
    "export type RegistryItem = {",
    "  name: string",
    "  type: string",
    "  title: string",
    "  description: string",
    "  dependencies?: string[]",
    "  registryDependencies?: string[]",
    "  files: RegistryItemFile[]",
    "}",
    "",
    `export const registryItems: RegistryItem[] = ${JSON.stringify(raw.items ?? [], null, 2)}`,
    "",
    "export function getRegistryItem(name: string): RegistryItem | undefined {",
    "  return registryItems.find((item) => item.name === name)",
    "}",
  ]
  const target = join(exampleSrc, "config", "registry.ts")
  await writeFile(target, lines.join("\n") + "\n")
  console.log("generated example/src/config/registry.ts")
}

async function warnUnregistered() {
  const files = await loadFiles()
  const registered = new Set(files.map((f) => examplePathFor(f.target)))
  async function walk(dir: string): Promise<string[]> {
    const out: string[] = []
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name)
      if (entry.isDirectory()) out.push(...(await walk(p)))
      else out.push(p)
    }
    return out
  }
  const bundles = join(exampleMessages, "registry")
  for (const file of [...(await walk(join(hooginDir, "ui"))), ...(await walk(bundles))]) {
    if (!registered.has(file) && !file.endsWith("registry.json")) {
      console.log(`  ! ${file} is not registered in registry/ui/registry.json`)
    }
  }
}

// Every component ships a bundle for every locale in the example's inlang
// settings, with the base locale's keys; a gap only shows up as English text.
async function warnMessageBundles() {
  const settings = JSON.parse(
    await readFile(join(exampleDir, "project.inlang", "settings.json"), "utf8")
  )
  const locales: string[] = settings.locales ?? []
  const base: string = settings.baseLocale ?? "en"
  const bundles = join(exampleMessages, "registry")
  const keysOf = async (file: string) =>
    Object.keys(JSON.parse(await readFile(file, "utf8")))
      .filter((key) => key !== "$schema")
      .sort()
      .join(",")
  for (const entry of await readdir(bundles, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const dir = join(bundles, entry.name)
    const present = new Set(await readdir(dir))
    const baseKeys = present.has(`${base}.json`)
      ? await keysOf(join(dir, `${base}.json`))
      : undefined
    for (const locale of locales) {
      if (!present.has(`${locale}.json`)) {
        console.log(`  ! ${entry.name}: missing locale ${locale}.json`)
      } else if (baseKeys !== undefined && locale !== base) {
        if ((await keysOf(join(dir, `${locale}.json`))) !== baseKeys) {
          console.log(`  ! ${entry.name}: keys differ between ${base}.json and ${locale}.json`)
        }
      }
    }
  }
}

async function syncAll() {
  const files = await loadFiles()
  for (const file of files) {
    const pair = pairFor(file)
    await syncPair(
      reverse
        ? { name: pair.name, from: pair.registry, to: pair.example }
        : { name: pair.name, from: pair.example, to: pair.registry }
    )
  }
  if (!reverse) {
    await warnUnregistered()
    await warnMessageBundles()
  }
  await generateRegistryConfig()
  console.log(`Synced ${files.length} file(s) (${reverse ? "registry → example" : "example → registry"}).`)
}

if (watchMode) {
  await syncAll()
  let timer: ReturnType<typeof setTimeout> | undefined
  // ponytail: debounced full re-sync on any change under the watched trees —
  // ~60 file copies, cheap; per-file watchers not worth the complexity.
  const source = reverse ? registryDir : [hooginDir, exampleMessages, exampleI18n]
  console.log(`Watching ${source} for changes...`)
  for (const dir of Array.isArray(source) ? source : [source]) {
    watch(dir, { recursive: true }, () => {
      clearTimeout(timer)
      timer = setTimeout(() => syncAll().catch((err) => console.error(err)), 100)
    })
  }
} else {
  await syncAll()
}
